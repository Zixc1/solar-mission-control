    def get_f107_series(self) -> List[Dict]:
        """Return the monthly F10.7 series with a centered 13-month smooth."""
        rows = [r for r in (self._get(ENDPOINTS['swpc_f107'], cache_minutes=360) or []) if isinstance(r, dict)]
        parsed = []
        for row in rows:
            tag = str(get_key(row, 'time-tag', 'time_tag', 'date', default=''))
            value = as_float(get_key(row, 'f10.7', 'f107', 'flux'), float('nan'))
            if tag and math.isfinite(value):
                stamp = parse_swpc_time(tag + '-01') if re.fullmatch(r'\d{4}-\d{2}', tag) else parse_swpc_time(tag)
                if stamp:
                    parsed.append({'time_tag': tag, 'timestamp': stamp, 'flux': value, 'smoothed_13m': None})
        parsed.sort(key=lambda row: row['timestamp'])
        for index in range(6, len(parsed)-6):
            parsed[index]['smoothed_13m'] = sum(r['flux'] for r in parsed[index-6:index+7]) / 13.0
        return parsed

