def initialize_run_database(output_dir: str) -> Tuple[sqlite3.Connection, str]:
    os.makedirs(output_dir, exist_ok=True)
    database_path = os.path.join(output_dir, 'solar_mission_control.db')
    connection = sqlite3.connect(database_path)
    existing = connection.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name='runs'"
    ).fetchone()
    required = {'run_id', 'started_at', 'ended_at', 'version',
                'status', 'output_dir', 'warning'}
    if existing:
        columns = {row[1] for row in connection.execute('PRAGMA table_info(runs)')}
        if not required.issubset(columns):
            suffix = datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')
            legacy_name = f'runs_legacy_{suffix}'
            connection.execute(f'ALTER TABLE runs RENAME TO "{legacy_name}"')
            print(f'  Legacy run table renamed to {legacy_name}')
    connection.execute("CREATE TABLE IF NOT EXISTS runs ("
                       "run_id TEXT PRIMARY KEY, started_at TEXT NOT NULL, "
                       "ended_at TEXT, version TEXT NOT NULL, status TEXT NOT NULL, "
                       "output_dir TEXT NOT NULL, warning TEXT)")
    run_id = str(uuid.uuid4())
    connection.execute(
        'INSERT INTO runs(run_id, started_at, version, status, output_dir) VALUES (?,?,?,?,?)',
        (run_id, datetime.now(timezone.utc).isoformat(), VERSION, 'running', output_dir))
    connection.commit()
    return connection, run_id

def cleanup_old_runs(connection: sqlite3.Connection, retention_days: int = 180) -> int:
    retention_days = max(1, int(retention_days))
    cutoff = (datetime.now(timezone.utc)-timedelta(days=retention_days)).isoformat()
    cursor = connection.execute(
        "DELETE FROM runs WHERE started_at < ? AND status != 'extreme_event'",
        (cutoff,))
    connection.commit()
    return cursor.rowcount


def close_run_database(connection: sqlite3.Connection, run_id: str,
                       status: str, warning: str = '') -> None:
    connection.execute(
        'UPDATE runs SET ended_at=?, status=?, warning=? WHERE run_id=?',
        (datetime.now(timezone.utc).isoformat(), status, warning, run_id))
    connection.commit()
    connection.close()


def write_pdf_report(text_report: str, visualizer: Optional[SpaceWeatherVisualizer],
                     output_dir: str) -> Optional[str]:
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet
        from reportlab.lib.units import cm
        from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer,
                                        Image as PDFImage, PageBreak, Preformatted)
    except ImportError:
        print('  PDF export skipped: ReportLab is not installed.')
        return None
    path = os.path.join(output_dir, 'solar_mission_control_report.pdf')
    styles = getSampleStyleSheet()
    document = SimpleDocTemplate(path, pagesize=A4, leftMargin=1.25*cm,
                                 rightMargin=1.25*cm, topMargin=1.2*cm,
                                 bottomMargin=1.2*cm)
    try:
        body = Preformatted(text_report, styles['Code'], maxLineLength=105)
    except TypeError:
        body = Preformatted(text_report, styles['Code'])

    story = [Paragraph('Solar Mission Control', styles['Title']),
             Paragraph(f'Version {VERSION}', styles['Normal']), Spacer(1, 12),
             body]
    if visualizer:
        for item in visualizer.figures + visualizer.images:
            image_path = item.get('path')
            if not image_path or not os.path.exists(image_path):
                continue
            try:
                story.extend([PageBreak(),
                              Paragraph(item.get('title', 'Plate'), styles['Heading2']),
                              Spacer(1, 8),
                              PDFImage(image_path, width=17*cm, height=9.6*cm,
                                       kind='proportional'),
                              Spacer(1, 6),
                              Paragraph(item.get('caption', ''), styles['BodyText'])])
            except Exception as exc:
                story.append(Paragraph(
                    f'[Image could not be embedded: {type(exc).__name__}]',
                    styles['Normal']))
    document.build(story)
    print(f'  PDF report written: {path}')
    return path

