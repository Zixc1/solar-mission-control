    def add_psp_wispr_gallery(self) -> None:
        """Add generated WISPR previews to the existing observatory gallery."""
        if not self.include_images:
            return
        context = (getattr(self.agg, 'psp_contexts', {}) or {}).get('wispr')
        if not context:
            if 'wispr' in (getattr(self.agg, 'psp_requested_keys', []) or []):
                self._unavailable('psp_wispr', 'Parker Solar Probe WISPR',
                                  'WISPR was requested but no FITS previews were produced.')
