            self.images.append({
                'key': f'psp_wispr_{index:02d}',
                'title': f'Parker Solar Probe WISPR frame {index}',
                'caption': ('WISPR FITS preview. Delayed inner-heliosphere imagery; '
                            'science context only and excluded from risk scoring.'),
                'path': preview,
                'source': 'PSP WISPR FITS',
                'observation_time_utc': context.get('preview_observed', {}).get(preview),
            })

