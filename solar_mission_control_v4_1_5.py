    def get_alerts(self) -> List[Dict]:
        """Return currently effective SWPC messages and retain recent/history groups."""
        data = self._get(ENDPOINTS['swpc_alerts'])
        rows = [item for item in (data or []) if isinstance(item, dict)]
        now = datetime.now(timezone.utc); recent_cutoff = now - timedelta(hours=72)
        active, recent, historical = [], [], []
        for item in rows:
            text = str(get_key(item, 'message', 'product_text', default=''))
            issued = parse_swpc_time(get_key(item, 'issue_datetime', 'issue_time', 'time_tag'))
            upper = text.upper()
            cancelled = any(token in upper for token in ('CANCEL WATCH', 'CANCEL WARNING', 'CANCEL ALERT'))
            summary = 'SUMMARY:' in upper or 'SPACE WEATHER MESSAGE CODE: SUMP' in upper
            explicit_end = parse_swpc_time(get_key(item, 'valid_to', 'expiration_time', 'end_time'))
            effective = (not cancelled and not summary and
                         ((explicit_end and explicit_end >= now) or (issued and issued >= recent_cutoff)))
            if effective:
                active.append(item)
            elif issued and issued >= recent_cutoff:
                recent.append(item)
            else:
                historical.append(item)
        self.recent_alert_messages = recent
        self.historical_alert_messages = historical
        return active

