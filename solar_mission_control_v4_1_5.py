def _alert_fingerprint(payload: Dict[str, Any]) -> str:
    """Return one stable fingerprint for storage, logs, and webhook results."""
    stable = {key: value for key, value in payload.items()
              if key not in {'run_id', 'generated_at'}}
    encoded = json.dumps(stable, sort_keys=True, default=str).encode('utf-8')
    return hashlib.sha256(encoded).hexdigest()


def _alert_db_path(db_path: Optional[str] = None) -> str:
    """Honour an operator override before falling back to the caller path."""
    return (os.getenv('SPACE_WEATHER_ALERT_DB', '').strip() or db_path or
            'swrl_report/alert_fingerprints.db')


def alert_was_recently_sent(payload: Dict[str, Any], cooldown_minutes: int = 60,
                            db_path: Optional[str] = None) -> bool:
    """Read duplicate state without recording an unconfirmed delivery."""
    path = _alert_db_path(db_path)
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    fingerprint = _alert_fingerprint(payload)
    cutoff = datetime.now(timezone.utc) - timedelta(
        minutes=max(1, int(cooldown_minutes)))
    connection = sqlite3.connect(path, timeout=10)
    try:
        connection.execute(
            'CREATE TABLE IF NOT EXISTS alert_fingerprints ('
            'fingerprint TEXT PRIMARY KEY, last_sent_at TEXT NOT NULL)')
        row = connection.execute(
            'SELECT last_sent_at FROM alert_fingerprints WHERE fingerprint=?',
            (fingerprint,)).fetchone()
        previous = parse_swpc_time(row[0]) if row else None
        return previous is not None and previous >= cutoff
    finally:
        connection.close()


def record_alert_sent(payload: Dict[str, Any],
                      db_path: Optional[str] = None) -> str:
    """Record a fingerprint only after confirmed webhook delivery."""
    path = _alert_db_path(db_path)
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    fingerprint = _alert_fingerprint(payload)
    now = datetime.now(timezone.utc)
    connection = sqlite3.connect(path, timeout=10)
    try:
        connection.execute(
            'CREATE TABLE IF NOT EXISTS alert_fingerprints ('
            'fingerprint TEXT PRIMARY KEY, last_sent_at TEXT NOT NULL)')
        connection.execute(
            'INSERT OR REPLACE INTO alert_fingerprints(fingerprint,last_sent_at) '
            'VALUES (?,?)', (fingerprint, now.isoformat()))
        connection.execute('DELETE FROM alert_fingerprints WHERE last_sent_at < ?',
                           ((now - timedelta(days=30)).isoformat(),))
        connection.commit()
        return fingerprint
    finally:
        connection.close()


def is_duplicate_alert(payload: Dict[str, Any], cooldown_minutes: int = 60,
                       db_path: Optional[str] = None) -> bool:
    """Backward-compatible, read-only duplicate check."""
    return alert_was_recently_sent(payload, cooldown_minutes, db_path)

def send_webhook_alert(payload: Dict[str, Any], dry_run: bool = False) -> Dict[str, Any]:
    fingerprint = _alert_fingerprint(payload)
    if dry_run:
        return {'dry_run': True, 'fingerprint': fingerprint, 'payload': payload}
    url = os.getenv('SPACE_WEATHER_WEBHOOK', '').strip()
    if not url:
        return {'skipped': 'SPACE_WEATHER_WEBHOOK is not configured',
                'fingerprint': fingerprint}
    try:
        response = requests.post(url, json=payload, timeout=10)
        response.raise_for_status()
        return {'sent': True, 'status_code': response.status_code,
                'fingerprint': fingerprint}
    except requests.exceptions.RequestException as exc:
        return {'error': f'Webhook delivery failed: {type(exc).__name__}',
                'fingerprint': fingerprint}

