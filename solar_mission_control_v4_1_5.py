    # here is the modification of _fetch_hmi for 2.4.4: the JSOC export
    # service has been replaced by the VSO backend. VSO does not need an
    # email notification address, so JSOC_EMAIL is no longer consulted
    # anywhere, and the request is served synchronously rather than
    # through the asynchronous JSOC export queue.
    #
    # The two HMI products are selected by their physical observable:
    #     a.Physobs.los_magnetic_field  -> hmi.M_45s line of sight
    #                                      magnetogram, in gauss
    #     a.Physobs.intensity           -> hmi.Ic_45s continuum
    #                                      intensity image
    #
    # The magnetogram is drawn with the diverging 'hmimag' colormap; the
    # continuum with greyscale.
    @staticmethod
    def _fido_file_count(result) -> int:
        try:
            return int(getattr(result, 'file_num', 0) or 0)
        except (TypeError, ValueError):
            return 0

    @staticmethod
    def _fido_latest_record(result):
        """Return the newest row from the newest non-empty Fido provider block."""
        candidates = []
        iterable = () if result is None else result
        for block in iterable:
            try:
                if len(block):
                    candidates.append(block[-1:])
            except (TypeError, IndexError):
                continue
        return candidates[-1] if candidates else None

    def _fetch_hmi(self, key: str, physobs, title: str, caption: str):
        """Fetch HMI through staged VSO searches, then optional explicit JSOC series."""
        end = Time.now()
        start = end - 24 * u.hour
        attempts = [
            ('instrument + physobs + sample',
             (a.Time(start, end), a.Instrument.hmi, physobs,
              a.Sample(45 * u.minute))),
            ('instrument + physobs',
             (a.Time(start, end), a.Instrument.hmi, physobs)),
        ]
        selected = None
        selected_method = None
        for description, attrs in attempts:
            try:
                result = Fido.search(*attrs)
                count = self._fido_file_count(result)
                print(f"  HMI {key}: VSO [{description}] matched {count} file(s).")
                if count:
                    selected = self._fido_latest_record(result)
                    if selected is not None:
                        selected_method = f'VSO {description}'
                        break
            except Exception as exc:
                print(f"  HMI {key}: VSO [{description}] failed: "
                      f"{type(exc).__name__}: {exc}")
        if selected is None:
            email = os.environ.get('JSOC_EMAIL', '').strip()
            if email:
                series_name = ('hmi.M_45s' if 'magnetogram' in key
                               else 'hmi.Ic_45s')
                try:
                    result = Fido.search(
                        a.Time(start, end), a.jsoc.Series(series_name),
                        a.jsoc.Notify(email))
                    count = self._fido_file_count(result)
                    print(f"  HMI {key}: JSOC {series_name} matched {count} file(s).")
                    if count:
                        selected = self._fido_latest_record(result)
                        selected_method = f'JSOC {series_name}'
                except Exception as exc:
                    print(f"  HMI {key}: JSOC fallback failed: "
                          f"{type(exc).__name__}: {exc}")
            else:
                print(f"  HMI {key}: JSOC fallback skipped; JSOC_EMAIL is not set.")
        if selected is None:
            return None
        files = Fido.fetch(selected, path=os.path.join(self.fits_dir, '{file}'))
        print(f"  HMI {key}: {selected_method} fetch returned "
              f"{len(files) if files else 0} local file(s).")
        if not files:
            return None
        fits_path = str(files[0])
        solar_map = sunpy.map.Map(fits_path)
        if isinstance(solar_map, list):
            solar_map = solar_map[0]
        cmap = 'hmimag' if 'magnetogram' in key else 'gray'
        return self._save_sunpy_map(
            solar_map, key, title,
            caption + f" Retrieval path: {selected_method}.",
            fits_path, cmap=cmap)

