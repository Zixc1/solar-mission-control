@dataclass
class DataQuality:
    """Data quality metrics for each source"""
    source: str
    completeness: float  # 0-100%
    freshness: float     # 0-100%
    reliability: float   # 0-100%
    record_count: int
    data_gaps: int
    flags: List[str] = field(default_factory=list)

    @property
    def overall_score(self) -> float:
        return (self.completeness + self.freshness + self.reliability) / 3

    @property
    def status(self) -> str:
        score = self.overall_score
        if score >= 90:
            return "Excellent"
        elif score >= 70:
            return "Good"
        elif score >= 50:
            return "Fair"
        else:
            return "Critical"


