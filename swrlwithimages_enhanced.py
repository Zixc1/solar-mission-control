    # Orchestration
    # ------------------------------------------------------------------

    def build_all(self, risk: Dict, events: Dict):
        """Draw every figure and collect every image"""
        if HAS_MATPLOTLIB:
            print("  Drawing figures...")
            self._apply_style()
            for builder in (self.plot_xray, self.plot_protons,
                            self.plot_solar_wind, self.plot_geomagnetic,
                            self.plot_cmes):
                try:
                    builder()
                except Exception as e:
                    # A single bad panel must not cost the whole report.
                    print(f"  Figure failed ({builder.__name__}): {e}")
            try:
                self.plot_overview(risk, events)
            except Exception as e:
                print(f"  Figure failed (plot_overview): {e}")
        else:
            print("  Matplotlib unavailable, skipping figures.")

        self.fetch_imagery()

    def display_inline(self):
        """Show the figures and images under the cell in a notebook"""
        if 'ipykernel' not in sys.modules:
            return
        try:
            from IPython.display import display, Image as IPImage, Markdown
        except ImportError:
            return

        for item in self.figures + self.images:
            try:
                display(Markdown(f"**{item['title']}**"))
                display(IPImage(filename=item['path']))
            except Exception:
                continue

