    # ------------------------------------------------------------------
    # Real-Time Solar Wind (RTSW) - L1 fleet
    # ------------------------------------------------------------------

    # here is the modification of the solar wind fetcher. This method
    # REPLACES both get_dscovr_solar_wind() and get_ace_solar_wind(),
    # which are deleted. Reasons:
    #
    #   1. Every endpoint they used returns 404 since 30 April 2026.
    #   2. The replacement RTSW files already contain all spacecraft in
    #      one payload with an "active" flag, so a manual DSCOVR-then-ACE
    #      fallback chain is not just broken, it is the wrong shape. When
    #      this was written the active spacecraft was SOLAR-1, which the
    #      old code had no branch for at all.
    #   3. Field names changed: density -> proton_density,
    #      speed -> proton_speed, temperature -> proton_temperature.
    #      The magnetometer fields bx_gsm, by_gsm, bz_gsm and bt kept
    #      their names.
    #
    # Mag and plasma are joined on (time_tag, source) rather than on
    # time_tag alone, because several spacecraft report the same minute
    # and joining on time alone would splice one satellite's field onto
    # another's plasma.
    def get_rtsw_solar_wind(self, active_only: bool = True) -> List[SolarWindData]:
        '''
        Fetch real-time solar wind from the RTSW L1 fleet.

        Parameters
        ----------
        active_only : bool
            If True, keep only records SWPC flagged as operational.
            Set False to see every spacecraft for comparison.

        Returns
        -------
        List of SolarWindData sorted by time.
        '''
        mag_data = self._get(ENDPOINTS['rtsw_mag'])
        wind_data = self._get(ENDPOINTS['rtsw_wind'])

        if not mag_data and not wind_data:
            return []

        # Index the magnetometer records by (time_tag, source).
        mag_by_key: Dict[Tuple[str, str], Dict] = {}
        if isinstance(mag_data, list):
            for item in mag_data:
                if not isinstance(item, dict):
                    continue
                key = (str(item.get('time_tag')), str(item.get('source')))
                mag_by_key[key] = {
                    'bx': as_float(item.get('bx_gsm')),
                    'by': as_float(item.get('by_gsm')),
                    'bz': as_float(item.get('bz_gsm')),
                    'bt': as_float(item.get('bt')),
                }

        results = []
        if isinstance(wind_data, list):
            for item in wind_data:
                if not isinstance(item, dict):
                    continue

                is_active = bool(item.get('active', False))
                if active_only and not is_active:
                    continue

                timestamp = parse_swpc_time(item.get('time_tag'))
                if timestamp is None:
                    continue

                source = str(item.get('source', 'RTSW'))
                mag = mag_by_key.get((str(item.get('time_tag')), source), {})

                results.append(SolarWindData(
                    timestamp=timestamp,
                    speed=as_float(item.get('proton_speed')),
                    density=as_float(item.get('proton_density')),
                    temperature=as_float(item.get('proton_temperature')),
                    bz=mag.get('bz', 0.0),
                    bt=mag.get('bt', 0.0),
                    bx=mag.get('bx', 0.0),
                    by=mag.get('by', 0.0),
                    source=source,
                    active=is_active
                ))

        results.sort(key=lambda x: x.timestamp)

        if results:
            self.active_sw_source = results[-1].source

        return results

