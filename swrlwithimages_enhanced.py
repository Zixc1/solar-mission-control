# here is the modification of the whole reporting concept: NEW class.
# Everything below this line is new. The text report could only quote
# single numbers ("Bz: -8.4 nT"), which hides the thing that actually
# matters operationally: how long the field has been southward, whether
# the flux is rising or decaying, whether a Kp peak is a spike or a
# sustained storm. This class draws the underlying time series and
# collects the current full disc imagery, then packs both into aBest ai model in alpaca list
# self-contained HTML report.
#
# Design rules used throughout:
#   * Every axis carries units, every threshold carries its NOAA scale
#     label, so a figure can be read without the surrounding text.
#   * Severity is the only thing allowed to use colour saturation; the
#     data traces stay in a quiet ink palette.
#   * Missing samples become NaN and are LEFT as gaps. Interpolating
#     across a telemetry dropout would invent measurements.
#   * Nothing here is allowed to raise. A failed figure or a dead image
#     URL drops out of the report and the run continues.
class SpaceWeatherVisualizer:
    """Builds figures, collects imagery, and writes the visual report"""

    # Palette: pale chart-paper ground with ink traces, and the NOAA
    # scale ramp reserved for severity so colour always means the same
    # thing across every panel.
    PALETTE = {
        'paper': '#EDEFF2',
        'panel': '#F9FAFB',
        'ink': '#101A2B',
        'muted': '#5A6779',
        'rule': '#C7CEDA',
        'primary': '#1B3A6B',
        'secondary': '#2E7D74',
        'tertiary': '#8A5A2B',
        'accent': '#7A3E8F',
    }

    # Index 0 = quiet, 5 = extreme. Shared by the R, S and G scales.
    SCALE_COLORS = ['#3F7D3A', '#B9A200', '#D98B12', '#C4551F',
                    '#A32B22', '#6E1414']

    def __init__(self, aggregator: SpaceWeatherAggregator,
                 output_dir: str = "swrl_report",
                 dpi: int = 140,
                 include_images: bool = True):
        self.agg = aggregator
