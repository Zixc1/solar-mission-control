# here is the modification of the format handling: NEW helper.
# SWPC changed several products from
#     [["time_tag", "Kp", ...], ["2026-...", "4", ...], ...]
# to
#     [{"time_tag": "2026-...", "Kp": 4, ...}, ...]
# This helper normalises BOTH shapes to a list of dicts, so the code
# keeps working whichever format a given endpoint is serving. Writing
# it this way rather than just switching to the new format means the
# script will not break again the next time SWPC migrates a product.
def normalise_swpc_product(data: Any) -> List[Dict]:
    '''
    Normalise a SWPC /products/ JSON payload to a list of dicts.

    Handles two layouts:
      1. Legacy: a list of lists, where the first inner list holds the
         column names and every later list holds the values.
      2. Current: a list of dicts, each already key-value.

    Returns an empty list for anything unrecognised.
    '''
    if not data or not isinstance(data, list):
        return []

    first = data[0]

    # Current format: already a list of dicts.
    if isinstance(first, dict):
        return [row for row in data if isinstance(row, dict)]

    # Legacy format: header row plus value rows.
    if isinstance(first, (list, tuple)):
        header = [str(h) for h in first]
        rows = []
        for values in data[1:]:
            if not isinstance(values, (list, tuple)):
                continue
            rows.append(dict(zip(header, values)))
        return rows

    return []


# here is the modification of the numeric parsing: NEW helper.
# The SCN also states the values "will be numeric, and will no longer
# be quoted". The old code did float(item[1]) if item[1] else 0, which
# silently turned a legitimate 0.0 into 0 and crashed on None. This
# accepts str, int, float or None from either format.
def as_float(value: Any, default: float = 0.0) -> float:
    '''Coerce a SWPC value to float, tolerating None, '' and strings.'''
    if value is None or value == '':
        return default
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


# here is the modification of the timestamp parsing: NEW helper.
# The RTSW files use '2026-09-05T03:56:00' (ISO, no Z, no microseconds).
# The old products used '2026-09-05 03:56:00.000'. GOES uses a trailing
# Z. One strict strptime format cannot cover all three, and the old code
# silently dropped every record it could not parse.
def parse_swpc_time(value: Any) -> Optional[datetime]:
    '''Parse any SWPC timestamp string to a timezone-aware UTC datetime.'''
    if not value:
        return None
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=timezone.utc)

    text = str(value).strip().replace('Z', '')

    for fmt in ('%Y-%m-%dT%H:%M:%S.%f',
                '%Y-%m-%dT%H:%M:%S',
                '%Y-%m-%dT%H:%M',
                '%Y-%m-%d %H:%M:%S.%f',
                '%Y-%m-%d %H:%M:%S',
                '%Y-%m-%d %H:%M'):
        try:
            return datetime.strptime(text, fmt).replace(tzinfo=timezone.utc)
        except ValueError:
            continue

    try:
        parsed = datetime.fromisoformat(text)
        return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)
    except ValueError:
        return None


# here is the modification of the key lookup: NEW helper.
# SWPC is inconsistent about capitalisation across products ('Kp' vs
# 'kp', 'Dst' vs 'dst'). Rather than guess, look the key up case
# insensitively and accept any of several aliases.
def get_key(row: Dict, *names: str, default: Any = None) -> Any:
    '''Fetch the first matching key from a dict, ignoring case.'''
    if not isinstance(row, dict):
        return default
    lowered = {str(k).lower(): v for k, v in row.items()}
    for name in names:
        if name in row:
            return row[name]
        if str(name).lower() in lowered:
            return lowered[str(name).lower()]
    return default


# here is the modification of the physics helpers: NEW function.
# The solar wind figure plots the Newell et al. (2007) coupling
# function, which is a far better predictor of the magnetospheric
# response than speed or Bz taken separately:
#
#     dPhi_MP/dt = v^(4/3) * B_T^(2/3) * sin^(8/3)(theta_c / 2)
#
# where
#     v       = solar wind bulk speed            [km/s]
#     B_T     = sqrt(By^2 + Bz^2), the IMF component transverse to the
#               Sun-Earth line, in GSM           [nT]
#     theta_c = atan2(By, Bz), the IMF clock angle measured from GSM
#               north; theta_c = 180 deg is purely southward IMF and
#               gives the maximum of the sine term.
#
# The exponents come from an empirical fit to the merging rate at the
# magnetopause, so the result is in the mixed units (km/s)^(4/3) nT^(2/3)
# and is normally read against its own long-term average of about
# 4421 in those units, which is the reference line drawn on the panel.
def newell_coupling(speed: float, by: float, bz: float) -> float:
    '''Newell coupling function dPhi_MP/dt in (km/s)^(4/3) nT^(2/3).'''
    try:
        b_t = math.hypot(by, bz)
        if speed <= 0:
            return float('nan')
        if b_t == 0:
            return 0.0
        theta_c = math.atan2(by, bz)
        return ((speed ** (4.0 / 3.0))
                * (b_t ** (2.0 / 3.0))
                * (abs(math.sin(theta_c / 2.0)) ** (8.0 / 3.0)))
    except (TypeError, ValueError, OverflowError):
        return float('nan')


# here is the modification of the plotting helpers: NEW function.
# Matplotlib will not draw a log axis through zero, and a missing
# sample must not be joined across by a straight line. Both cases are
# mapped to NaN, which matplotlib leaves as a gap.
def blank_if_zero(value: Any) -> float:
    '''Return NaN for a missing, zero or negative sample.'''
    v = as_float(value, default=float('nan'))
    if v is None:
        return float('nan')
    if v != v:  # NaN
        return float('nan')
    return v if v > 0 else float('nan')


