@dataclass
class SolarWindData:
    """Real-time solar wind measurements"""
    timestamp: datetime
    speed: float        # km/s
    density: float      # p/cm^3
    temperature: float  # K
    bz: float           # nT
    bt: float           # nT
    bx: Optional[float] = None
    by: Optional[float] = None
    source: str = "Unknown"
    # here is the modification of SolarWindData: NEW field.
    # The RTSW files carry records from several spacecraft at the same
    # timestamp, only one of which is the operational source. Keeping
    # the flag lets the report say which spacecraft it is quoting.
    active: bool = True

    # here is the modification of SolarWindData: NEW derived properties,
    # so the plotting code does not have to recompute them and the two
    # definitions cannot drift apart.
    @property
    def dynamic_pressure(self) -> float:
        '''Solar wind dynamic pressure P = 1.67e-6 n v^2, in nPa.'''
        return 1.67e-6 * self.density * (self.speed ** 2)

    @property
    def coupling(self) -> float:
        '''Newell coupling function for this sample.'''
        return newell_coupling(self.speed, self.by or 0.0, self.bz)


