class SolarMissionControl:
    """Main application class"""

    # here is the modification of the application constructor: it now
    # owns the visual configuration as well, and holds the visualizer
    # so a caller (a notebook cell, for instance) can reach the figure
    # paths after run() returns.
    def __init__(self, nasa_api_key: str = NASA_API_KEY,
                 output_dir: str = "swrl_report",
                 with_plots: bool = True,
                 with_images: bool = True,
                 write_html: bool = True):
        self.aggregator = SpaceWeatherAggregator(nasa_api_key)
        self.output_dir = output_dir
        self.with_plots = with_plots and (HAS_MATPLOTLIB or with_images)
        self.with_images = with_images
        self.write_html = write_html
        self.visualizer: Optional[SpaceWeatherVisualizer] = None
        self.report_generator = SpaceWeatherReportGenerator(self.aggregator)

    def run(self, quick_check: bool = False, hours_back: int = 48,
            hours_forward: int = 48):
        """Run the space weather monitoring system"""
        print("\n" + "=" * 80)
        print("         SOLAR MISSION CONTROL - Space Weather Monitoring System")
        print("=" * 80 + "\n")

        self.aggregator.fetch_all_data(hours_back=hours_back,
                                       hours_forward=hours_forward)

        print("\n" + "-" * 80 + "\n")
        print(self.report_generator.generate_quick_check())

        # here is the modification of the run sequence. Visuals are built
        # BEFORE the text report is generated, because the report now
        # contains an inventory of the figures, and the inventory can
        # only be written once the figures exist. The risk and event
        # dictionaries are computed once here and passed down rather than
        # recomputed inside the visualizer.
        if self.with_plots and not quick_check:
            conditions, risk = self.report_generator._risk_inputs()
            events = self.aggregator.get_recent_events(hours=72)

            self.visualizer = SpaceWeatherVisualizer(
                self.aggregator,
                output_dir=self.output_dir,
                include_images=self.with_images
            )
            self.report_generator.visualizer = self.visualizer
            self.visualizer.build_all(risk, events)

        if not quick_check:
            report_text = self.report_generator.generate_full_report()
            print(report_text)

            # The plain-text report is written next to the figures so the
            # whole run is one self-contained folder.
            try:
                os.makedirs(self.output_dir, exist_ok=True)
                text_path = os.path.join(self.output_dir,
                                         'space_weather_report.txt')
                with open(text_path, 'w', encoding='utf-8') as handle:
                    handle.write(report_text)
                print(f"  Text report written: {text_path}")
            except OSError as e:
                print(f"  Could not write text report: {e}")

            if self.visualizer and self.write_html:
                conditions, risk = self.report_generator._risk_inputs()
                self.visualizer.build_html_report(report_text, conditions, risk)

            # Under a notebook, show the plates beneath the cell as well.
            if self.visualizer:
                self.visualizer.display_inline()

        conditions = self.aggregator.get_current_conditions()
        return conditions['xray']['classification']


