        for entry in IMAGE_SOURCES:
            fetched = None
            for url in entry['urls']:
                fetched = self.api.fetch_image(url)
                if fetched:
                    break

            if not fetched:
                print(f"  Skipping {entry['key']}: no source responded")
                continue

            content, mime = fetched
            extension = mimetypes.guess_extension(mime) or '.jpg'
            if extension == '.jpe':
                extension = '.jpg'
            path = os.path.join(self.image_dir, f"{entry['key']}{extension}")
            try:
                with open(path, 'wb') as handle:
                    handle.write(content)
            except OSError as e:
                print(f"  Could not write {path}: {e}")
                continue

            self.images.append({'key': entry['key'], 'title': entry['title'],
                                'caption': entry['caption'], 'path': path,
                                'mime': mime, 'url': url})
            print(f"  Image written: {path}")

        return self.images

