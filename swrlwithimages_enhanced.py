class SunPyAstropyIntegration:
    """Integration with SunPy and Astropy for additional solar data"""

    def __init__(self):
        self.has_sunpy = HAS_SUNPY
        self.has_astropy = HAS_ASTROPY

    def get_goes_flares_sunpy(self, start_date: datetime,
                              end_date: datetime) -> List[SolarFlare]:
        """Fetch GOES flare data from the HEK via SunPy"""
        if not self.has_sunpy:
            return []

        try:
            time_range = TimeRange(start_date, end_date)
            result = Fido.search(
                a.Time(time_range),
                a.hek.EventType('FL'),
                a.hek.OBS.Observatory == 'GOES'
            )

            flares = []
            if len(result) > 0 and len(result[0]) > 0:
                for record in result[0]:
                    try:
                        start = parse_swpc_time(record.get('event_starttime'))
                        if start is None:
                            continue
                        peak = parse_swpc_time(record.get('event_peaktime'))
                        end = parse_swpc_time(record.get('event_endtime'))

                        class_type = record.get('fl_goescls') or 'Unknown'

                        # here is the modification of the HEK flare
                        # intensity: the original hard-coded intensity=0
                        # with a "would need to parse" comment, so every
                        # HEK flare scored zero in the risk engine. The
                        # same parser used for DONKI now runs here.
                        intensity = SpaceWeatherAPI._parse_flare_intensity(
                            None, class_type)

                        flares.append(SolarFlare(
                            start_time=start,
                            peak_time=peak,
                            end_time=end,
                            class_type=class_type,
                            intensity=intensity,
                            location=record.get('hgs_coord', None),
                            active_region=record.get('ar_noaanum', None),
                            source="SunPy/HEK"
                        ))
                    except Exception:
                        continue

            return flares
        except Exception as e:
            print(f"SunPy flare search error: {e}")
            return []

    def get_current_time_astropy(self) -> datetime:
        """Get current UTC time using Astropy"""
        if not self.has_astropy:
            return datetime.now(timezone.utc)

        try:
            return Time.now().datetime.replace(tzinfo=timezone.utc)
        except Exception:
            return datetime.now(timezone.utc)

    def convert_coordinates(self, lat: float, lon: float) -> Optional[str]:
        """Convert heliographic coordinates to a NsEw string"""
        # here is the modification of convert_coordinates: the original
        # returned a TUPLE on the no-astropy branch and a STRING on the
        # astropy branch, so a caller doing string formatting on the
        # result would work or fail depending on whether astropy was
        # installed. Both branches now return the same string.
        try:
            ns = "N" if lat >= 0 else "S"
            ew = "E" if lon >= 0 else "W"
            return f"{ns}{abs(lat):.0f}{ew}{abs(lon):.0f}"
        except (TypeError, ValueError):
            return None


