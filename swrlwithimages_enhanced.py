    # ------------------------------------------------------------------
    # Figure 3 - RTSW solar wind stack
    # ------------------------------------------------------------------

    def plot_solar_wind(self) -> Optional[str]:
        """Five-panel L1 solar wind stack including the Newell coupling"""
        if not HAS_MATPLOTLIB or not self.agg.solar_wind_data:
            return None

        data = self.agg.solar_wind_data
        times = [d.timestamp for d in data]
        source = self.agg.solar_wind_data[-1].source

        fig, axes = plt.subplots(5, 1, figsize=(9.5, 11.5), sharex=True,
                                 gridspec_kw={'hspace': 0.12})

        # Panel 1: bulk speed, with the stream-classification levels.
        speed = [blank_if_zero(d.speed) for d in data]
        axes[0].plot(times, speed, lw=1.1, color=self.PALETTE['primary'])
        # here is the modification of the speed panel: a threshold is only
        # drawn when the wind comes near it. Drawing the 800 km/s line
        # during a 350 km/s quiet period squashed the whole trace into
        # the bottom fifth of the panel and hid the structure in it.
        finite_speed = [v for v in speed if v == v]
        speed_ceiling = max(finite_speed) if finite_speed else 0.0
        for level, color_index, label in ((500, 1, 'enhanced'),
                                          (600, 2, 'high speed stream'),
                                          (800, 4, 'very high speed')):
            if level > speed_ceiling * 1.12:
                continue
            axes[0].axhline(level, color=self.SCALE_COLORS[color_index],
                            lw=0.8, ls='--', alpha=0.8)
            axes[0].text(0.985, level, label,
                         transform=axes[0].get_yaxis_transform(),
                         ha='right', va='bottom', fontsize=7,
                         color=self.SCALE_COLORS[color_index])
        axes[0].set_ylabel('$v$  [km s$^{-1}$]')
        axes[0].set_title(f'Solar wind at L1  ({source})')

        # Panel 2: proton density.
        density = [blank_if_zero(d.density) for d in data]
        axes[1].plot(times, density, lw=1.0, color=self.PALETTE['secondary'])
        axes[1].set_ylabel('$n_p$  [cm$^{-3}$]')

        # Panel 3: temperature, log scale because it spans decades
        # between slow wind and a shock passage.
        temperature = [blank_if_zero(d.temperature) for d in data]
        axes[2].plot(times, temperature, lw=1.0, color=self.PALETTE['tertiary'])
        axes[2].set_yscale('log')
        axes[2].set_ylabel('$T_p$  [K]')

        # Panel 4: IMF. Bz is the geoeffective component, so the
        # southward excursions are filled: area below zero is roughly
        # what the ring current integrates.
        bz = [as_float(d.bz) for d in data]
        bt = [as_float(d.bt) for d in data]
        axes[3].plot(times, bt, lw=0.9, color=self.PALETTE['muted'],
                     label='$B_t$')
        axes[3].plot(times, bz, lw=1.1, color=self.PALETTE['primary'],
                     label='$B_z$ (GSM)')
        axes[3].axhline(0, color=self.PALETTE['ink'], lw=0.8)
        try:
            axes[3].fill_between(times, bz, 0,
                                 where=[value < 0 for value in bz],
                                 color=self.SCALE_COLORS[4], alpha=0.22,
                                 interpolate=True, label='southward IMF')
        except Exception:
            pass
        axes[3].set_ylabel('$B$  [nT]')
        axes[3].legend(loc='upper left', ncol=3)

        # Panel 5: Newell coupling function. This is the panel to read
        # first when asking whether the magnetosphere is actually being
        # driven, since it folds speed, transverse field and clock angle
        # into one quantity.
        coupling = [d.coupling for d in data]
        axes[4].plot(times, coupling, lw=1.0, color=self.PALETTE['accent'])
        axes[4].axhline(4421, color=self.PALETTE['muted'], lw=0.8, ls='--')
        axes[4].text(0.985, 4421, 'long-term average', ha='right', va='bottom',
                     fontsize=7, color=self.PALETTE['muted'],
                     transform=axes[4].get_yaxis_transform())
        axes[4].set_ylabel(r'$d\Phi_{MP}/dt$'
                           '\n'
                           r'[(km s$^{-1}$)$^{4/3}$ nT$^{2/3}$]')
        axes[4].set_xlabel('Time (UTC)')

        for ax in axes:
            self._time_axis(ax)

        return self._save(
            fig, 'solar_wind', f'Solar wind at L1 ({source})',
            'The bottom panel is the Newell coupling function, '
            'v^(4/3) B_T^(2/3) sin^(8/3)(theta_c/2), an empirical merging '
            'rate at the magnetopause. Sustained excursions above its '
            'long-term average predict the geomagnetic response better than '
            'speed or Bz taken alone, and lead the Kp response by roughly '
            'the convection timescale.')

    # ------------------------------------------------------------------
    # Figure 4 - geomagnetic response
    # ------------------------------------------------------------------

    def plot_geomagnetic(self) -> Optional[str]:
        """Observed and forecast Kp, with Dst underneath"""
        if not HAS_MATPLOTLIB:
            return None
        if not self.agg.kp_data and not self.agg.kp_forecast and not self.agg.dst_data:
            return None

        fig, axes = plt.subplots(2, 1, figsize=(9.5, 6.4), sharex=True,
                                 gridspec_kw={'hspace': 0.16,
                                              'height_ratios': [1.15, 1]})

        bar_width = 3.0 / 24.0  # Kp is a three-hourly index

        observed_times, observed_values = [], []
        for row in self.agg.kp_data:
            stamp = parse_swpc_time(row.get('time_tag'))
            if stamp is None:
                continue
            observed_times.append(stamp)
            observed_values.append(as_float(row.get('kp')))

        forecast_times, forecast_values = [], []
        for row in self.agg.kp_forecast:
            stamp = parse_swpc_time(row.get('time_tag'))
            if stamp is None:
                continue
            forecast_times.append(stamp)
            forecast_values.append(as_float(row.get('kp')))

        def kp_color(value: float) -> str:
            return self.SCALE_COLORS[self.agg._kp_to_g_scale(value)]

        if observed_times:
            # align='edge': the time tag OPENS the three-hour interval,
            # so a centred bar would place the bin 90 minutes early.
            axes[0].bar(observed_times, observed_values, width=bar_width,
                        align='edge',
                        color=[kp_color(v) for v in observed_values],
                        edgecolor=self.PALETTE['panel'], linewidth=0.4)
        if forecast_times:
            # Forecast bars are hatched and half opaque so a predicted
            # storm is never mistaken for an observed one.
            axes[0].bar(forecast_times, forecast_values, width=bar_width,
                        align='edge',
                        color=[kp_color(v) for v in forecast_values],
                        alpha=0.45, hatch='///',
                        edgecolor=self.PALETTE['panel'], linewidth=0.4)

        axes[0].axhline(5, color=self.SCALE_COLORS[1], lw=0.9, ls='--')
        axes[0].text(0.985, 5, 'G1 storm threshold', ha='right', va='bottom',
                     fontsize=7, color=self.SCALE_COLORS[1],
                     transform=axes[0].get_yaxis_transform())
        axes[0].set_ylim(0, 9)
        axes[0].set_yticks(range(0, 10))
        axes[0].set_ylabel('$K_p$')
        axes[0].set_title('Geomagnetic activity: observed and forecast')
        axes[0].legend(handles=[
            Patch(facecolor=self.PALETTE['muted'], label='observed'),
            Patch(facecolor=self.PALETTE['muted'], alpha=0.45, hatch='///',
                  label='forecast'),
        ], loc='upper left', ncol=2)

        dst_times, dst_values = [], []
        for row in self.agg.dst_data:
            stamp = parse_swpc_time(row.get('time_tag'))
            if stamp is None:
                continue
            dst_times.append(stamp)
            dst_values.append(as_float(row.get('dst')))

        if dst_times:
            axes[1].plot(dst_times, dst_values, lw=1.2,
                         color=self.PALETTE['primary'])
            axes[1].fill_between(dst_times, dst_values, 0,
                                 where=[v < 0 for v in dst_values],
                                 color=self.PALETTE['primary'], alpha=0.15,
                                 interpolate=True)
            for level, color_index, label in ((-30, 1, 'weak storm'),
                                              (-50, 2, 'moderate'),
                                              (-100, 3, 'intense'),
                                              (-250, 5, 'super storm')):
                axes[1].axhline(level, color=self.SCALE_COLORS[color_index],
                                lw=0.7, ls='--', alpha=0.8)
                axes[1].text(0.985, level, label, ha='right', va='bottom',
                             fontsize=7, color=self.SCALE_COLORS[color_index],
                             transform=axes[1].get_yaxis_transform())
        else:
            axes[1].text(0.5, 0.5, 'Dst unavailable', ha='center', va='center',
                         transform=axes[1].transAxes,
                         color=self.PALETTE['muted'])

        axes[1].axhline(0, color=self.PALETTE['ink'], lw=0.8)
        axes[1].set_ylabel('Dst  [nT]')
        axes[1].set_xlabel('Time (UTC)')

        for ax in axes:
            self._time_axis(ax)

        return self._save(
            fig, 'geomagnetic', 'Geomagnetic activity',
            'Bar colour is the NOAA G-scale; hatched bars are forecast. Dst '
            'below tracks the ring current directly, so a deep excursion '
            'there confirms that a Kp spike was a genuine storm main phase '
            'rather than a single disturbed three-hour interval.')

    # ------------------------------------------------------------------
    # Figure 5 - CME population
    # ------------------------------------------------------------------

    def plot_cmes(self) -> Optional[str]:
        """CME speed against launch time, Earth-directed events marked"""
        if not HAS_MATPLOTLIB or not self.agg.cmes:
            return None

        cmes = self.agg.cmes
        fig, ax = plt.subplots(figsize=(9.5, 4.4))

        def marker_size(cme: CME) -> float:
            # Area scales with the angular width, so a halo event is
            # visibly the large marker it deserves to be.
            half_angle = cme.half_angle if cme.half_angle else 20.0
            return max(25.0, min(420.0, (half_angle ** 1.6) / 2.0))

        other = [c for c in cmes if not c.is_earth_directed]
        earth = [c for c in cmes if c.is_earth_directed]

        if other:
            ax.scatter([c.start_time for c in other], [c.speed for c in other],
                       s=[marker_size(c) for c in other],
                       facecolor='none', edgecolor=self.PALETTE['muted'],
                       linewidth=1.0, label='not Earth-directed')
        if earth:
            ax.scatter([c.start_time for c in earth], [c.speed for c in earth],
                       s=[marker_size(c) for c in earth],
                       facecolor=self.SCALE_COLORS[3], alpha=0.55,
                       edgecolor=self.SCALE_COLORS[4], linewidth=1.0,
                       label='Earth-directed')

        # Regime line: above roughly 750 km/s a CME normally drives a
        # fast forward shock at 1 AU.
        ax.axhline(750, color=self.PALETTE['muted'], lw=0.8, ls='--')
        ax.text(0.985, 750, 'shock-driving regime', ha='right', va='bottom',
                fontsize=7, color=self.PALETTE['muted'],
                transform=ax.get_yaxis_transform())

        now = datetime.now(timezone.utc)
        for cme in earth[:6]:
            eta = self.agg.estimate_cme_eta(cme)
            if not eta:
                continue
            hours = (eta - now).total_seconds() / 3600
            label = (f"ETA +{hours:.0f} h" if hours > 0
                     else f"arrived {abs(hours):.0f} h ago")
            ax.annotate(label, xy=(cme.start_time, cme.speed),
                        xytext=(0, 14), textcoords='offset points',
                        ha='center', fontsize=7.5,
                        color=self.PALETTE['ink'])

        # Headroom so the ETA annotations do not run into the title.
        lower, upper = ax.get_ylim()
        ax.set_ylim(lower, upper + (upper - lower) * 0.16)

        ax.set_ylabel('Plane-of-sky speed  [km s$^{-1}$]')
        ax.set_xlabel('Launch time (UTC)')
        ax.set_title('CMEs catalogued by DONKI')
        ax.legend(loc='upper left', markerscale=0.45)
        self._time_axis(ax)

        return self._save(
            fig, 'cme_population', 'CME population',
            'Speeds are the plane-of-sky fits, so an Earth-directed halo is '
            'projected and its true radial speed is higher than plotted. '
            'ETAs use the WSA-Enlil arrival where DONKI supplies one and a '
            'drag relaxation towards a 400 km/s ambient wind otherwise.')

    # ------------------------------------------------------------------
    # Figure 6 - activity and risk overview
    # ------------------------------------------------------------------

    def plot_overview(self, risk: Dict, events: Dict) -> Optional[str]:
        """Flare tally and the weighted risk breakdown side by side"""
        if not HAS_MATPLOTLIB:
            return None

        fig, axes = plt.subplots(1, 2, figsize=(9.5, 3.8),
                                 gridspec_kw={'wspace': 0.42})

        counts = events['flares']['by_class']
        classes = ['A', 'B', 'C', 'M', 'X']
        values = [counts.get(c, 0) for c in classes]
        severity = [0, 0, 1, 3, 5]
        axes[0].bar(classes, values,
                    color=[self.SCALE_COLORS[s] for s in severity],
                    width=0.62)
        for index, value in enumerate(values):
            axes[0].text(index, value, str(value), ha='center', va='bottom',
                         fontsize=9, color=self.PALETTE['ink'])
        axes[0].set_ylabel('events in 72 h')
        axes[0].set_title('Flare tally by class')
        axes[0].set_ylim(0, max(values + [1]) * 1.25)
        axes[0].grid(axis='x', visible=False)

        components = [('X-ray', risk['xray_risk'], 0.30),
                      ('Protons', risk['proton_risk'], 0.25),
                      ('Geomagnetic', risk['geomagnetic_risk'], 0.25),
                      ('Solar wind', risk['solar_wind_risk'], 0.20)]
        labels = [f"{name} x{weight:.2f}" for name, _, weight in components]
        scores = [score for _, score, _ in components]
        positions = list(range(len(components)))

        def risk_color(score: float) -> str:
            if score >= 80:
                return self.SCALE_COLORS[5]
            if score >= 60:
                return self.SCALE_COLORS[4]
            if score >= 40:
                return self.SCALE_COLORS[3]
            if score >= 20:
                return self.SCALE_COLORS[2]
            return self.SCALE_COLORS[0]

        axes[1].barh(positions, scores,
                     color=[risk_color(s) for s in scores], height=0.6)
        axes[1].set_yticks(positions)
        axes[1].set_yticklabels(labels)
        axes[1].invert_yaxis()
        axes[1].set_xlim(0, 100)
        axes[1].set_xlabel('component risk  [0-100]')
        axes[1].set_title(f"Weighted risk: {risk['level']} "
                          f"({risk['overall_risk']}/100)")
        axes[1].axvline(risk['overall_risk'], color=self.PALETTE['ink'],
                        lw=1.2, ls=(0, (4, 3)))
        axes[1].grid(axis='y', visible=False)
        for position, score in zip(positions, scores):
            axes[1].text(score + 1.5, position, str(int(score)),
                         va='center', fontsize=8, color=self.PALETTE['ink'])

        return self._save(
            fig, 'overview', 'Activity and risk overview',
            'The dashed vertical line is the weighted total, so a component '
            'bar reaching past it is what is currently carrying the score.')

