# RISK ASSESSMENT ENGINE
# ============================================================================

class RiskAssessmentEngine:
    """Calculates risk levels from space weather data"""

    def __init__(self):
        self.weights = {
            'xray': 0.30,
            'proton': 0.25,
            'geomagnetic': 0.25,
            'solar_wind': 0.20
        }

    def calculate_xray_risk(self, flux: float, classification: str) -> Tuple[int, str]:
        """Calculate X-ray risk (0-100)"""
        if not classification or classification == "N/A":
            return 0, "No data"

        classification = str(classification).upper()

        if classification.startswith('X'):
            try:
                val = float(classification[1:])
                if val >= 10:
                    return 100, "Extreme X-ray event"
                elif val >= 5:
                    return 90, "Major X-ray event"
                elif val >= 1:
                    return 70, "Significant X-ray event"
            except ValueError:
                pass
            return 60, "X-class flare"
        elif classification.startswith('M'):
            try:
                val = float(classification[1:])
                if val >= 5:
                    return 50, "Strong M-class flare"
            except ValueError:
                pass
            return 40, "M-class flare"
        elif classification.startswith('C'):
            return 20, "Minor C-class activity"

        return 5, "Background levels"

    def calculate_proton_risk(self, flux_10mev: float) -> Tuple[int, str]:
        """Calculate proton radiation risk (0-100)"""
        if flux_10mev >= 100000:
            return 100, "Extreme proton storm (S5)"
        elif flux_10mev >= 10000:
            return 85, "Severe proton storm (S4)"
        elif flux_10mev >= 1000:
            return 65, "Strong proton storm (S3)"
        elif flux_10mev >= 100:
            return 45, "Moderate proton storm (S2)"
        elif flux_10mev >= 10:
            return 25, "Minor proton storm (S1)"
        return 5, "No significant proton activity"

    def calculate_geomagnetic_risk(self, kp: float) -> Tuple[int, str]:
        """Calculate geomagnetic activity risk (0-100)"""
        if kp >= 9:
            return 100, "Extreme geomagnetic storm (G5)"
        elif kp >= 8:
            return 85, "Severe geomagnetic storm (G4)"
        elif kp >= 7:
            return 65, "Strong geomagnetic storm (G3)"
        elif kp >= 6:
            return 45, "Moderate geomagnetic storm (G2)"
        elif kp >= 5:
            return 25, "Minor geomagnetic storm (G1)"
        return 5, "Quiet geomagnetic conditions"

    def calculate_solar_wind_risk(self, speed: float, bz: float,
                                  density: float) -> Tuple[int, str]:
        """Calculate solar wind impact risk (0-100)"""
        risk = 0
        reasons = []

        if speed >= 800:
            risk += 40
            reasons.append("Very high speed stream")
        elif speed >= 600:
            risk += 25
            reasons.append("High speed stream")
        elif speed >= 500:
            risk += 15
            reasons.append("Elevated solar wind speed")
        elif speed >= 400:
            risk += 5
            reasons.append("Moderate solar wind")

        # Southward Bz is the geoeffective sign: it opens dayside
        # reconnection with Earth's northward field.
        if bz <= -20:
            risk += 40
            reasons.append("Strongly southward IMF")
        elif bz <= -10:
            risk += 25
            reasons.append("Southward IMF")
        elif bz <= -5:
            risk += 10
            reasons.append("Weakly southward IMF")

        if density >= 20:
            risk += 20
            reasons.append("High solar wind density")
        elif density >= 10:
            risk += 10
            reasons.append("Elevated solar wind density")

        reason = ", ".join(reasons) if reasons else "Normal solar wind conditions"
        return min(100, risk), reason

    def calculate_overall_risk(self, xray_flux: float, xray_class: str,
                               proton_flux: float, kp: float,
                               solar_wind_speed: float, bz: float,
                               density: float) -> Dict:
        """Calculate overall space weather risk assessment"""

        xray_risk, xray_reason = self.calculate_xray_risk(xray_flux, xray_class)
        proton_risk, proton_reason = self.calculate_proton_risk(proton_flux)
        geo_risk, geo_reason = self.calculate_geomagnetic_risk(kp)
        sw_risk, sw_reason = self.calculate_solar_wind_risk(solar_wind_speed, bz, density)

        overall = (
            xray_risk * self.weights['xray'] +
            proton_risk * self.weights['proton'] +
            geo_risk * self.weights['geomagnetic'] +
            sw_risk * self.weights['solar_wind']
        )

        risks = {
            'X-Ray': xray_risk,
            'Proton': proton_risk,
            'Geomagnetic': geo_risk,
            'Solar Wind': sw_risk
        }
        dominant = max(risks, key=risks.get)

        if overall >= 80:
            level = "EXTREME"
        elif overall >= 60:
            level = "SEVERE"
        elif overall >= 40:
            level = "MODERATE"
        elif overall >= 20:
            level = "MINOR"
        else:
            level = "NOMINAL"

        concerns = []
        if xray_risk >= 40:
            concerns.append("Elevated solar X-ray activity")
        if proton_risk >= 40:
            concerns.append("Elevated radiation environment")
        if geo_risk >= 40:
            concerns.append("Geomagnetic disturbance")
        if sw_risk >= 40:
            concerns.append("Enhanced solar wind conditions")

        return {
            'overall_risk': int(overall),
            'level': level,
            'xray_risk': xray_risk,
            'proton_risk': proton_risk,
            'geomagnetic_risk': geo_risk,
            'solar_wind_risk': sw_risk,
            'dominant_factor': dominant,
            'concerns': concerns if concerns else ["No significant concerns"],
            'xray_reason': xray_reason,
            'proton_reason': proton_reason,
            'geo_reason': geo_reason,
            'sw_reason': sw_reason
        }


