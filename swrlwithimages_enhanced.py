class SpaceWeatherAPI:
    """Handles all API requests to space weather data sources"""

    def __init__(self, nasa_api_key: str = NASA_API_KEY, timeout: int = 30):
        self.nasa_api_key = nasa_api_key
        self.timeout = timeout
        self.session = requests.Session()
        self.session.headers.update({
            'User-Agent': f'SolarMissionControl/{VERSION}',
            'Accept': 'application/json'
        })
        self._cache = {}
        self._cache_expiry = {}
        # here is the modification of the API client: NEW attribute.
        # Records which L1 spacecraft supplied the solar wind data so the
        # report can name it. With the RTSW files this is no longer a
        # constant.
        self.active_sw_source = "Unknown"

    def _get(self, url: str, params: Dict = None, cache_minutes: int = 5) -> Optional[Any]:
        """Make a GET request with caching and error handling"""
        cache_key = f"{url}:{json.dumps(params or {}, sort_keys=True)}"

        if cache_key in self._cache:
            if datetime.now() < self._cache_expiry.get(cache_key, datetime.min):
                return self._cache[cache_key]

        try:
            response = self.session.get(url, params=params, timeout=self.timeout)
            response.raise_for_status()
            data = response.json()

            self._cache[cache_key] = data
            self._cache_expiry[cache_key] = datetime.now() + timedelta(minutes=cache_minutes)

            return data
        except requests.exceptions.RequestException as e:
            print(f"API Error ({url}): {e}")
            return None
        except json.JSONDecodeError as e:
            print(f"JSON Parse Error ({url}): {e}")
            return None

    # here is the modification of the API client: NEW binary fetcher.
    # _get() calls response.json() unconditionally, so it cannot be used
    # for the observatory imagery. This method returns raw bytes plus the
    # MIME type, and refuses anything that is not an image, because a
    # dead observatory path often answers with an HTML error page and a
    # 200 status rather than a 404.
    def fetch_image(self, url: str) -> Optional[Tuple[bytes, str]]:
        '''
        Download an image. Returns (bytes, mime_type) or None.
        '''
        try:
            response = self.session.get(url, timeout=self.timeout,
                                        headers={'Accept': 'image/*'})
            response.raise_for_status()

            content_type = (response.headers.get('Content-Type') or '').lower()
            if not content_type.startswith('image/'):
                guessed, _ = mimetypes.guess_type(url)
                if not (guessed or '').startswith('image/'):
                    print(f"  Not an image ({content_type or 'unknown type'}): {url}")
                    return None
                content_type = guessed

            content = response.content
            if not content or len(content) < 1024:
                print(f"  Image too small to be real: {url}")
                return None

            return content, content_type.split(';')[0].strip()
        except requests.exceptions.RequestException as e:
            print(f"  Image fetch failed ({url}): {e}")
            return None

