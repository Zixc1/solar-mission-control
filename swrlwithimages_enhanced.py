    def _time_axis(self, ax, mark_now: bool = True):
        """Format a datetime x-axis and optionally mark the current time"""
        locator = mdates.AutoDateLocator(minticks=4, maxticks=9)
        ax.xaxis.set_major_locator(locator)
        ax.xaxis.set_major_formatter(
            mdates.ConciseDateFormatter(locator, tz=timezone.utc))
        if mark_now:
            ax.axvline(datetime.now(timezone.utc), color=self.PALETTE['ink'],
                       lw=0.8, ls=(0, (4, 3)), alpha=0.55, zorder=1)

    def _save(self, fig, key: str, title: str, caption: str) -> Optional[str]:
        """Write a figure to disk and register it for the report"""
        try:
            path = os.path.join(self.figure_dir, f"{key}.png")
            fig.savefig(path, bbox_inches='tight')
            plt.close(fig)
            self.figures.append({'key': key, 'title': title,
                                 'caption': caption, 'path': path})
            print(f"  Figure written: {path}")
            return path
        except Exception as e:
            print(f"  Could not save figure {key}: {e}")
            try:
                plt.close(fig)
            except Exception:
                pass
            return None

    @staticmethod
    def _window(data: List, hours: float) -> List:
        """Keep only records inside the trailing time window"""
        cutoff = datetime.now(timezone.utc) - timedelta(hours=hours)
        return [d for d in data if getattr(d, 'timestamp', None)
                and d.timestamp >= cutoff]

    # ------------------------------------------------------------------
    # Figure 1 - GOES X-ray flux
    # ------------------------------------------------------------------

    def plot_xray(self) -> Optional[str]:
        """GOES soft X-ray flux with the A-X classification bands"""
        if not HAS_MATPLOTLIB or not self.agg.xray_data:
            return None

        data = self.agg.xray_data
        times = [d.timestamp for d in data]
        long_channel = [blank_if_zero(d.flux_long) for d in data]
        short_channel = [blank_if_zero(d.flux_short) for d in data]

        fig, ax = plt.subplots(figsize=(9.5, 4.4))

        # The flare classes are decade bands in the 0.1-0.8 nm channel.
        # Shading them removes the mental arithmetic of reading a
        # logarithmic flux and converting it to a letter class.
        bands = [(1e-8, 1e-7, 0, 0.05), (1e-7, 1e-6, 0, 0.05),
                 (1e-6, 1e-5, 1, 0.09), (1e-5, 1e-4, 3, 0.13),
                 (1e-4, 1e-2, 5, 0.18)]
        for lower, upper, severity, shade in bands:
            ax.axhspan(lower, upper, color=self.SCALE_COLORS[severity],
                       alpha=shade, zorder=0)
            ax.axhline(lower, color=self.PALETTE['rule'], lw=0.6, zorder=0)

        ax.plot(times, long_channel, lw=1.3, color=self.PALETTE['primary'],
                label='0.1-0.8 nm (long, classification channel)')
        ax.plot(times, short_channel, lw=0.9, color=self.PALETTE['tertiary'],
                alpha=0.85, label='0.05-0.4 nm (short)')

        ax.set_yscale('log')
        ax.set_ylim(1e-9, 1e-3)
        ax.set_ylabel('X-ray irradiance  [W m$^{-2}$]')
        ax.set_xlabel('Time (UTC)')
        ax.set_title('GOES soft X-ray flux')
        ax.legend(loc='upper left', ncol=2)
        self._time_axis(ax)

        # Class letters on the right, placed at the geometric centre of
        # each decade band.
        letters = ax.twinx()
        letters.set_yscale('log')
        letters.set_ylim(ax.get_ylim())
        letters.set_yticks([3.16e-9, 3.16e-8, 3.16e-7, 3.16e-6,
                            3.16e-5, 3.16e-4])
        letters.set_yticklabels(['', 'A', 'B', 'C', 'M', 'X'])
        letters.tick_params(length=0, labelsize=10, colors=self.PALETTE['ink'])
        letters.grid(False)

        # Annotate the strongest event in the window; that is the number
        # the executive summary quotes as the 24 h peak.
        try:
            peak = max((d for d in data if d.flux_long > 0),
                       key=lambda d: d.flux_long)
            ax.annotate(f"peak {self.agg._flux_to_class(peak.flux_long)}",
                        xy=(peak.timestamp, peak.flux_long),
                        xytext=(0, 16), textcoords='offset points',
                        ha='center', fontsize=8, color=self.PALETTE['ink'],
                        arrowprops=dict(arrowstyle='-', lw=0.8,
                                        color=self.PALETTE['muted']))
        except ValueError:
            pass

        return self._save(
            fig, 'xray_flux', 'GOES soft X-ray flux',
            'Long channel in the classification band; the shaded decades are '
            'the A to X classes. A flare is the impulsive rise followed by a '
            'slower thermal decay, so a trace still high on the decay is a '
            'recent event rather than a new one.')

