class SpaceWeatherAggregator:
    """Aggregates data from all sources"""

    def __init__(self, nasa_api_key: str = NASA_API_KEY):
        self.api = SpaceWeatherAPI(nasa_api_key)
        self.sunpy_astropy = SunPyAstropyIntegration()
        self.risk_engine = RiskAssessmentEngine()

        self.xray_data: List[XRayData] = []
        self.proton_data: List[ProtonData] = []
        self.solar_wind_data: List[SolarWindData] = []
        self.flares: List[SolarFlare] = []
        self.cmes: List[CME] = []
        self.geomagnetic_storms: List[GeomagneticStorm] = []
        self.kp_data: List[Dict] = []
        self.kp_forecast: List[Dict] = []
        self.alerts: List[Dict] = []
        self.flare_probabilities: Dict = {}
        self.dst_data: List[Dict] = []

        self.data_quality: Dict[str, DataQuality] = {}
        self.last_update: Optional[datetime] = None

    def fetch_all_data(self, hours_back: int = 48, hours_forward: int = 48):
        """Fetch all space weather data"""
        print("Fetching space weather data from all sources...")

        now = datetime.now(timezone.utc)
        start_date = now - timedelta(hours=hours_back)
        end_date = now + timedelta(hours=hours_forward)

        print("  Fetching GOES satellite data...")
        self.xray_data = self.api.get_xray_data(days=3)
        self.proton_data = self.api.get_proton_data(days=3)

        self.data_quality['GOES'] = self._assess_data_quality(
            "GOES Satellite", self.xray_data,
            expected_interval_minutes=1, max_age_minutes=10
        )

        # here is the modification of the solar wind fetch. The original
        # called get_dscovr_solar_wind() and, if that returned fewer than
        # ten records, fell back to get_ace_solar_wind(). Both hit
        # endpoints NOAA removed on 30 April 2026, so both returned []
        # and the report showed zeros for speed, density and Bz. There is
        # now a single RTSW call covering the whole L1 fleet; SWPC itself
        # decides which spacecraft is operational via the "active" flag,
        # so no fallback chain is needed.
        print("  Fetching RTSW solar wind data (L1 fleet)...")
        self.solar_wind_data = self.api.get_rtsw_solar_wind(active_only=True)

        if self.solar_wind_data:
            print(f"  Active solar wind source: {self.api.active_sw_source}")
        else:
            # If nothing is flagged active, show every spacecraft rather
            # than reporting zeros as if they were measurements.
            print("  No active-flagged records; retrying without the filter...")
            self.solar_wind_data = self.api.get_rtsw_solar_wind(active_only=False)

        self.data_quality['RTSW'] = self._assess_data_quality(
            f"RTSW L1 ({self.api.active_sw_source})", self.solar_wind_data,
            expected_interval_minutes=1, max_age_minutes=15
        )

        print("  Fetching NOAA SWPC data...")
        self.kp_data = self.api.get_kp_index()
        self.kp_forecast = self.api.get_kp_forecast()
        self.alerts = self.api.get_alerts()
        self.flare_probabilities = self.api.get_flare_probabilities()
        self.dst_data = self.api.get_dst_index()

        self.data_quality['SWPC'] = self._assess_swpc_quality()

        print("  Fetching NASA DONKI data...")
        self.flares = self.api.get_donki_flares(start_date, end_date)
        self.cmes = self.api.get_donki_cmes(start_date, end_date)
        self.geomagnetic_storms = self.api.get_donki_geomagnetic_storms(start_date, end_date)

        self.data_quality['DONKI'] = self._assess_donki_quality()

        if self.sunpy_astropy.has_sunpy:
            print("  Fetching additional data via SunPy...")
            sunpy_flares = self.sunpy_astropy.get_goes_flares_sunpy(start_date, now)
            existing_times = {f.start_time for f in self.flares}
            for flare in sunpy_flares:
                if flare.start_time not in existing_times:
                    self.flares.append(flare)

        self.last_update = now
        print("Data fetch complete.")

    def _assess_data_quality(self, source: str, data: List,
                             expected_interval_minutes: int = 1,
                             max_age_minutes: int = 10) -> DataQuality:
        """Assess data quality for a given dataset"""
        flags = []

        if not data:
            return DataQuality(
                source=source, completeness=0, freshness=0, reliability=0,
                record_count=0, data_gaps=0, flags=["No data available"]
            )

        record_count = len(data)
        now = datetime.now(timezone.utc)

        try:
            latest = max(d.timestamp for d in data if hasattr(d, 'timestamp'))
            age_minutes = (now - latest).total_seconds() / 60
            freshness = max(0.0, 100 - (age_minutes / max_age_minutes) * 100)
            if freshness < 50:
                flags.append("Data may be stale")
        except (ValueError, AttributeError, TypeError):
            freshness = 0.0
            flags.append("Cannot determine data freshness")

        data_gaps = 0
        if len(data) > 1:
            sorted_data = sorted(
                (d for d in data if hasattr(d, 'timestamp')),
                key=lambda x: x.timestamp
            )
            for i in range(1, len(sorted_data)):
                gap = (sorted_data[i].timestamp
                       - sorted_data[i - 1].timestamp).total_seconds() / 60
                if gap > expected_interval_minutes * 3:
                    data_gaps += 1

        if data_gaps > 0:
            flags.append(f"{data_gaps} data gaps detected")

        expected_records = 24 * 60 / expected_interval_minutes
        completeness = min(100.0, (record_count / expected_records) * 100)
        if completeness < 50:
            flags.append("Low data completeness")

        reliability = (freshness * 0.4 + completeness * 0.4
                       + (100 - min(100, data_gaps * 10)) * 0.2)

        return DataQuality(
            source=source, completeness=completeness, freshness=freshness,
            reliability=reliability, record_count=record_count,
            data_gaps=data_gaps, flags=flags
        )

    def _assess_swpc_quality(self) -> DataQuality:
        """Assess SWPC data quality"""
        flags = []
        total_records = len(self.kp_data) + len(self.alerts)

        if not self.kp_data:
            flags.append("No Kp data")
        if not self.alerts:
            flags.append("No alerts data")

        completeness = min(100.0, total_records / 50 * 100)

        freshness = 0.0
        if self.kp_data:
            # here is the modification of the Kp freshness check: routed
            # through parse_swpc_time. The original called
            # datetime.fromisoformat() on a value SWPC formats as
            # '2026-09-05 03:00:00.000', which fromisoformat rejects on
            # older Python, so freshness silently came out as zero.
            latest_dt = parse_swpc_time(self.kp_data[-1].get('time_tag'))
            if latest_dt:
                age = (datetime.now(timezone.utc) - latest_dt).total_seconds() / 3600
                freshness = max(0.0, 100 - age * 10)
            else:
                flags.append("Cannot parse Kp timestamps")

        reliability = (completeness * 0.5 + freshness * 0.5)
        data_gaps = len([f for f in flags if 'No' in f])

        return DataQuality(
            source="NOAA Space Weather Prediction Center",
            completeness=completeness, freshness=freshness,
            reliability=reliability, record_count=total_records,
            data_gaps=data_gaps, flags=flags if flags else ["None"]
        )

    def _assess_donki_quality(self) -> DataQuality:
        """Assess DONKI data quality"""
        flags = []
        total_records = len(self.flares) + len(self.cmes) + len(self.geomagnetic_storms)

        completeness = min(100.0, total_records / 60 * 100)
        freshness = 50.0 if total_records > 0 else 0.0
        if total_records == 0:
            flags.append("No recent events")

        reliability = (completeness * 0.6 + freshness * 0.4)

        return DataQuality(
            source="NASA DONKI", completeness=completeness, freshness=freshness,
            reliability=reliability, record_count=total_records, data_gaps=0,
            flags=flags if flags else ["Data may be stale"]
        )

    def get_current_conditions(self) -> Dict:
        """Get current space weather conditions"""
        now = datetime.now(timezone.utc)

        current_xray = None
        current_xray_class = "N/A"
        peak_24h_xray = None
        peak_24h_class = "N/A"
        avg_24h_xray = 0.0

        if self.xray_data:
            # here is the modification of the "current" X-ray window. The
            # original required a sample within 300 s, so any delay in the
            # GOES feed left current_flux as None, which then blew up the
            # report formatter. The window is widened to 30 minutes and
            # falls back to the most recent sample regardless of age.
            recent = [x for x in self.xray_data
                      if (now - x.timestamp).total_seconds() < 1800]
            if not recent:
                recent = self.xray_data[-1:]
            if recent:
                current_xray = recent[-1].flux_long
                current_xray_class = self._flux_to_class(current_xray)

            last_24h = [x for x in self.xray_data
                        if (now - x.timestamp).total_seconds() < 86400]
            if last_24h:
                peak_24h_xray = max(x.flux_long for x in last_24h)
                peak_24h_class = self._flux_to_class(peak_24h_xray)
                avg_24h_xray = sum(x.flux_long for x in last_24h) / len(last_24h)

        xray_trend = "Stable"
        if self.xray_data and len(self.xray_data) >= 60:
            recent_avg = sum(x.flux_long for x in self.xray_data[-30:]) / 30
            older_avg = sum(x.flux_long for x in self.xray_data[-60:-30]) / 30
            if older_avg > 0:
                if recent_avg > older_avg * 1.5:
                    xray_trend = "Rising"
                elif recent_avg < older_avg * 0.67:
                    xray_trend = "Falling"

        current_proton_10 = 0.0
        current_proton_50 = 0.0
        current_proton_100 = 0.0
        peak_72h_proton = 0.0

        if self.proton_data:
            recent = [p for p in self.proton_data
                      if (now - p.timestamp).total_seconds() < 1800]
            if not recent:
                recent = self.proton_data[-1:]
            if recent:
                current_proton_10 = recent[-1].flux_10mev
                current_proton_50 = recent[-1].flux_50mev
                current_proton_100 = recent[-1].flux_100mev

            last_72h = [p for p in self.proton_data
                        if (now - p.timestamp).total_seconds() < 259200]
            if last_72h:
                peak_72h_proton = max(p.flux_10mev for p in last_72h)

        current_sw_speed = 0.0
        current_sw_density = 0.0
        current_sw_temp = 0.0
        current_bz = 0.0
        current_bt = 0.0
        # here is the modification of the conditions dict: bx, by and the
        # Newell coupling are carried through as well. Without by, any
        # caller wanting the coupling function had to assume by = 0,
        # which forces the clock angle to 0 or 180 deg and throws the
        # value away. The text report and the solar wind figure now read
        # the same number from the same place.
        current_bx = 0.0
        current_by = 0.0
        current_coupling = float('nan')
        sw_source = "No data"

        if self.solar_wind_data:
            latest = self.solar_wind_data[-1]
            current_sw_speed = latest.speed
            current_sw_density = latest.density
            current_sw_temp = latest.temperature
            current_bz = latest.bz
            current_bt = latest.bt
            current_bx = latest.bx if latest.bx is not None else 0.0
            current_by = latest.by if latest.by is not None else 0.0
            current_coupling = latest.coupling
            sw_source = latest.source

        current_kp = 0.0
        max_24h_kp = 0.0
        min_24h_kp = 9.0

        if self.kp_data:
            current_kp = self.kp_data[-1].get('kp', 0.0)
            for kp in self.kp_data[-8:]:
                kp_val = kp.get('kp', 0.0)
                max_24h_kp = max(max_24h_kp, kp_val)
                min_24h_kp = min(min_24h_kp, kp_val)
        else:
            min_24h_kp = 0.0

        current_dst = 0.0
        if self.dst_data:
            current_dst = self.dst_data[-1].get('dst', 0.0)

        s_scale = self._proton_to_s_scale(current_proton_10)
        proton_storm = current_proton_10 >= 10
        g_scale = self._kp_to_g_scale(current_kp)
        r_scale = self._flux_to_r_scale(current_xray or 0.0)

        if current_bz <= -10 and current_sw_speed >= 500:
            geoeffectiveness = "High"
        elif current_bz <= -5 or current_sw_speed >= 450:
            geoeffectiveness = "Moderate"
        elif current_bz < 0:
            geoeffectiveness = "Low"
        else:
            geoeffectiveness = "Very Low"

        return {
            'xray': {
                'current_flux': current_xray,
                'classification': current_xray_class,
                'r_scale': r_scale,
                'peak_24h': peak_24h_xray,
                'peak_24h_class': peak_24h_class,
                'avg_24h': avg_24h_xray,
                'trend': xray_trend
            },
            'protons': {
                'flux_10mev': current_proton_10,
                'flux_50mev': current_proton_50,
                'flux_100mev': current_proton_100,
                's_scale': s_scale,
                'storm_active': proton_storm,
                'peak_72h': peak_72h_proton
            },
            'solar_wind': {
                'speed': current_sw_speed,
                'density': current_sw_density,
                'temperature': current_sw_temp,
                'bz': current_bz,
                'bt': current_bt,
                'bx': current_bx,
                'by': current_by,
                'coupling': current_coupling,
                'geoeffectiveness': geoeffectiveness,
                'source': sw_source
            },
            'geomagnetic': {
                'kp': current_kp,
                'g_scale': g_scale,
                'dst': current_dst,
                'max_24h_kp': max_24h_kp,
                'min_24h_kp': min_24h_kp
            }
        }

    def get_recent_events(self, hours: int = 72) -> Dict:
        """Get summary of recent events"""
        now = datetime.now(timezone.utc)
        cutoff = now - timedelta(hours=hours)

        recent_flares = [f for f in self.flares if f.start_time >= cutoff]

        flare_counts = {'X': 0, 'M': 0, 'C': 0, 'B': 0, 'A': 0}
        significant_flares = []

        for flare in recent_flares:
            class_letter = flare.class_type[0].upper() if flare.class_type else 'A'
            if class_letter in flare_counts:
                flare_counts[class_letter] += 1
            if class_letter in ('X', 'M'):
                significant_flares.append(flare)

        recent_cmes = [c for c in self.cmes if c.start_time >= cutoff]
        earth_directed_cmes = [c for c in recent_cmes if c.is_earth_directed]

        cme_stats = {
            'total': len(recent_cmes),
            'earth_directed': len(earth_directed_cmes),
            'avg_speed': (sum(c.speed for c in recent_cmes) / len(recent_cmes)
                          if recent_cmes else 0.0),
            'max_speed': max((c.speed for c in recent_cmes), default=0.0),
            'min_speed': min((c.speed for c in recent_cmes), default=0.0)
        }

        recent_storms = [s for s in self.geomagnetic_storms if s.start_time >= cutoff]

        return {
            'flares': {
                'total': len(recent_flares),
                'by_class': flare_counts,
                'significant': significant_flares,
                'all': recent_flares
            },
            'cmes': {
                'stats': cme_stats,
                'earth_directed': earth_directed_cmes,
                'all': recent_cmes
            },
            'geomagnetic_storms': recent_storms
        }

    def get_threats(self, hours_forward: int = 48) -> List[str]:
        """Identify current and upcoming threats"""
        threats = []
        now = datetime.now(timezone.utc)

        recent_flares = [f for f in self.flares
                         if (now - f.start_time).total_seconds() < 86400
                         and str(f.class_type).upper().startswith('X')]
        if recent_flares:
            threats.append(f"{len(recent_flares)} X-class flare(s) in past 24 hours")

        for cme in self.cmes:
            if not cme.is_earth_directed:
                continue

            if cme.estimated_arrival:
                hours_until = (cme.estimated_arrival - now).total_seconds() / 3600
            elif cme.speed > 0:
                # here is the modification of the CME travel-time estimate.
                # The original used the full 1 AU Sun-Earth distance and a
                # CONSTANT speed. Both are wrong: L1 sits about 1.5e6 km
                # sunward of Earth, and fast CMEs decelerate against the
                # ambient wind through drag. A drag-based correction now
                # relaxes the CME toward a 400 km/s ambient wind, which is
                # the standard first-order model and typically shifts the
                # arrival estimate by hours for a fast event.
                hours_until = (self.estimate_cme_eta(cme) - now).total_seconds() / 3600
            else:
                continue

            if 0 < hours_until <= hours_forward:
                threats.append(
                    f"Earth-directed CME arrival in ~{int(hours_until)} hours "
                    f"({int(cme.speed)} km/s)"
                )

        if self.proton_data:
            recent_protons = [p for p in self.proton_data
                              if (now - p.timestamp).total_seconds() < 3600]
            if recent_protons:
                max_proton = max(p.flux_10mev for p in recent_protons)
                if max_proton >= 10:
                    threats.append(
                        f"Elevated proton flux: {max_proton:.1f} pfu "
                        f"(S{self._proton_to_s_scale(max_proton)} storm)"
                    )

        if self.kp_data:
            current_kp = self.kp_data[-1].get('kp', 0.0)
            if current_kp >= 5:
                threats.append(
                    f"Active geomagnetic storm: Kp={current_kp} "
                    f"(G{self._kp_to_g_scale(current_kp)})"
                )

        for forecast in self.kp_forecast[:12]:
            kp = forecast.get('kp', 0.0)
            if kp >= 5:
                threats.append(
                    f"Forecast geomagnetic storm: Kp={kp} at "
                    f"{forecast.get('time_tag', 'unknown')}"
                )
                break

        if self.solar_wind_data:
            latest = self.solar_wind_data[-1]
            if latest.speed >= 600:
                threats.append(f"High-speed solar wind stream: {latest.speed:.0f} km/s")
            if latest.bz <= -10:
                threats.append(f"Strongly southward IMF: Bz={latest.bz:.1f} nT")

        return threats

    # here is the modification of the CME arrival estimate: PROMOTED to a
    # method. The drag-based calculation used to live inline inside
    # get_threats(), while the report section and now the CME figure
    # needed the same number and each had its own copy - the events
    # section still used the naive 1 AU / v estimate, so the same CME
    # could be quoted with two different ETAs in one report. One
    # implementation now serves all three.
    #
    #   d      = 1 AU - 1.5e6 km, the Sun to L1 path
    #   v_amb  = 400 km/s ambient solar wind
    #   gamma  = 1e-7 km^-1 drag parameter
    #
    # A CME faster than the ambient wind is decelerated, a slower one is
    # dragged up towards it, which is why the sign is carried explicitly.
    def estimate_cme_eta(self, cme: CME) -> Optional[datetime]:
        '''Predicted L1 arrival for a CME, using its Enlil time if given.'''
        if cme.estimated_arrival:
            return cme.estimated_arrival
        if not cme.speed or cme.speed <= 0 or not cme.start_time:
            return None

        distance_km = 1.496e8 - 1.5e6
        ambient = 400.0
        gamma = 1.0e-7  # km^-1, typical drag parameter
        v0 = cme.speed

        if abs(v0 - ambient) < 1.0:
            v_eff = ambient
        else:
            sign = 1.0 if v0 > ambient else -1.0
            v_eff = ambient + sign * (
                abs(v0 - ambient)
                / (1.0 + sign * gamma * abs(v0 - ambient) * distance_km * 0.5)
            )

        travel_time_hours = (distance_km / max(v_eff, 200.0)) / 3600
        return cme.start_time + timedelta(hours=travel_time_hours)

    def _flux_to_class(self, flux: float) -> str:
        """Convert X-ray flux to flare classification"""
        if not flux or flux <= 0:
            return "N/A"

        if flux >= 1e-4:
            return f"X{flux / 1e-4:.1f}"
        elif flux >= 1e-5:
            return f"M{flux / 1e-5:.1f}"
        elif flux >= 1e-6:
            return f"C{flux / 1e-6:.1f}"
        elif flux >= 1e-7:
            return f"B{flux / 1e-7:.1f}"
        else:
            return f"A{flux / 1e-8:.1f}"

    def _flux_to_r_scale(self, flux: float) -> Tuple[int, str]:
        """Convert X-ray flux to NOAA R-scale"""
        if flux >= 2e-3:
            return 5, "R5 (Extreme)"
        elif flux >= 1e-3:
            return 4, "R4 (Severe)"
        elif flux >= 1e-4:
            return 3, "R3 (Strong)"
        elif flux >= 5e-5:
            return 2, "R2 (Moderate)"
        elif flux >= 1e-5:
            return 1, "R1 (Minor)"
        return 0, "R0 (None)"

    def _proton_to_s_scale(self, flux_10mev: float) -> int:
        """Convert proton flux to NOAA S-scale"""
        if flux_10mev >= 100000:
            return 5
        elif flux_10mev >= 10000:
            return 4
        elif flux_10mev >= 1000:
            return 3
        elif flux_10mev >= 100:
            return 2
        elif flux_10mev >= 10:
            return 1
        return 0

    def _kp_to_g_scale(self, kp: float) -> int:
        """Convert Kp index to NOAA G-scale"""
        if kp >= 9:
            return 5
        elif kp >= 8:
            return 4
        elif kp >= 7:
            return 3
        elif kp >= 6:
            return 2
        elif kp >= 5:
            return 1
        return 0


